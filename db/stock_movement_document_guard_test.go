// The guard follows the document id, so renaming a shipped delivery after the
// fact cannot make its movement deletable through an old reference.
func TestDeleteStockMovementRefusedAfterDeliveryRenamed(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGRNITestFixture(t, d, "org-mv-renamed-del", 10, 250)
	fx.receive(t, d, "GR-0001", 10)
	delivery := fx.ship(t, d, "DN-0001", 5)

	renamed := "DN-0002"
	items := echoDeliveryLines(t, d, delivery.ID)
	if _, err := d.UpdateDelivery(delivery.ID, UpdateDeliveryRequest{
		DeliveryNumber: &renamed, LineItems: &items,
	}); err != nil {
		t.Fatalf("UpdateDelivery(rename): %v", err)
	}

	movements := documentMovements(t, d, fx.productID, "DN-0001")
	if len(movements) != 1 {
		t.Fatalf("delivery movements = %d, want 1: %+v", len(movements), movements)
	}
	assertStockMovementDeleteRefused(t, d, movements[0].ID, "cannot delete a movement generated by delivery DN-0002")
}

// Completing a production order consumes components and produces the finished
// good; both sides are document stock history and neither may be deleted.
func TestDeleteStockMovementRefusedForProductionOrderMovements(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	f := seedProductionOrderFixture(t, d, false)

	order, err := d.CreateProductionOrder(CreateProductionOrderRequest{
		OrganizationID: f.orgID, OrderNumber: "PRO-0001", FinishedProductID: f.finished.ID,
		Quantity: 2, Date: f.date,
	})
	if err != nil {
		t.Fatalf("CreateProductionOrder: %v", err)
	}
	if _, err := d.UpdateProductionOrderStatus(order.ID, "completed", nil); err != nil {
		t.Fatalf("UpdateProductionOrderStatus(completed): %v", err)
	}

	consumed := documentMovements(t, d, f.componentA.ID, "PRO-0001")
	if len(consumed) != 1 || consumed[0].Type != "out" {
		t.Fatalf("component movements = %+v, want one production out", consumed)
	}
	produced := documentMovements(t, d, f.finished.ID, "PRO-0001")
	if len(produced) != 1 || produced[0].Type != "in" {
		t.Fatalf("finished movements = %+v, want one production in", produced)
	}

	assertStockMovementDeleteRefused(t, d, consumed[0].ID, "cannot delete a movement generated by production order PRO-0001")
	assertStockMovementDeleteRefused(t, d, produced[0].ID, "cannot delete a movement generated by production order PRO-0001")
}

// Every non-serialized delivery/receipt movement must carry the document id,
// including the restoring/reversing half written on cancel. Readers (the
// serialized cancel lookups and GetProductSummary's id joins) then resolve the
// real document instead of falling back to a reference match.
func TestDeliveryMovementsCarrySourceDocumentID(t *testing.T) {
	t.Parallel()

	t.Run("delivery", func(t *testing.T) {
		t.Parallel()
		d := newTestDB(t)
		fx := newGRNITestFixture(t, d, "org-mv-src-del", 10, 250)
		fx.receive(t, d, "GR-0001", 10)
		delivery := fx.ship(t, d, "DN-0001", 5)
		if _, err := d.UpdateDeliveryStatus(delivery.ID, "cancelled", nil); err != nil {
			t.Fatalf("UpdateDeliveryStatus(cancelled): %v", err)
		}

		movements := documentMovements(t, d, fx.productID, "DN-0001")
		if len(movements) != 2 {
			t.Fatalf("delivery movements = %d, want 2: %+v", len(movements), movements)
		}
		for _, m := range movements {
			if m.SourceDocumentID == nil || *m.SourceDocumentID != delivery.ID {
				t.Fatalf("movement %s sourceDocumentId = %v, want %q", m.ID, m.SourceDocumentID, delivery.ID)
			}
		}

		summary, err := d.GetProductSummary(fx.orgID, fx.productID)
		if err != nil {
			t.Fatalf("GetProductSummary: %v", err)
		}
		found := false
		for _, m := range summary.RecentMovements {
			if m.Reference != nil && *m.Reference == "DN-0001" {
				found = true
				if m.DocumentID == nil || *m.DocumentID != delivery.ID {
					t.Fatalf("summary movement documentId = %v, want delivery %q", m.DocumentID, delivery.ID)
				}
			}
		}
		if !found {
			t.Fatalf("delivery movements missing from product summary: %+v", summary.RecentMovements)
		}
	})

	t.Run("receipt", func(t *testing.T) {
		t.Parallel()
		d := newTestDB(t)
		fx := newGRNITestFixture(t, d, "org-mv-src-recv", 10, 250)
		receipt := fx.receive(t, d, "GR-0001", 10)
		if _, err := d.UpdateInboundDeliveryStatus(receipt.ID, "cancelled", nil); err != nil {
			t.Fatalf("UpdateInboundDeliveryStatus(cancelled): %v", err)
		}

		movements := documentMovements(t, d, fx.productID, "GR-0001")
		if len(movements) != 2 {
			t.Fatalf("receipt movements = %d, want 2: %+v", len(movements), movements)
		}
		for _, m := range movements {
			if m.SourceDocumentID == nil || *m.SourceDocumentID != receipt.ID {
				t.Fatalf("movement %s sourceDocumentId = %v, want %q", m.ID, m.SourceDocumentID, receipt.ID)
			}
		}
	})
}

// Moving an approved bill to another PO changes what its posted entry was
// built from, so it must be refused — while a header save that resends the
// unchanged PO (the form always does) still succeeds.
func TestUpdateIncomingInvoiceRefusesPOChangeWithPostedEntry(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-bill-po-change")

	createPO := func(number string) string {
		t.Helper()
		po, err := d.CreatePurchaseOrder(CreatePurchaseOrderRequest{
			OrganizationID: fx.orgID, VendorID: &fx.vendorID, OrderNumber: number, OrderDate: fx.date,
			LineItems: []CreatePurchaseOrderLineItemRequest{
				{ProductID: &fx.productID, Description: "Widget", Quantity: 1, UnitPrice: 1000},
			},
		})
		if err != nil {
			t.Fatalf("CreatePurchaseOrder(%s): %v", number, err)
		}
		return po.ID
	}
	po1 := createPO("PO-A")
	po2 := createPO("PO-B")

	subTotal, taxTotal := int64(1000), int64(200)
	bill, err := d.CreateIncomingInvoice(CreateIncomingInvoiceRequest{
		OrganizationID: fx.orgID, VendorID: fx.vendorID, PurchaseOrderID: &po1,
		VendorInvoiceNumber: "BILL-PO-1", Date: fx.date, Currency: "EUR",
		SubTotal: subTotal, TaxTotal: taxTotal, Total: subTotal + taxTotal,
		LineItems: []CreateInvoiceLineItemRequest{
			{Quantity: 1, UnitPrice: 1000, TaxRate: &fx.taxRateID, ProductID: &fx.productID},
		},
	})
	if err != nil {
		t.Fatalf("CreateIncomingInvoice: %v", err)
	}
	if _, err := d.UpdateIncomingInvoiceState(bill.ID, "approved"); err != nil {
		t.Fatalf("UpdateIncomingInvoiceState(approved): %v", err)
	}

	_, err = d.UpdateIncomingInvoice(bill.ID, UpdateIncomingInvoiceRequest{PurchaseOrderID: &po2})
	if err == nil {
		t.Fatal("expected moving an approved bill to another PO to be refused")
	}
	var verr *ValidationError
	if !errors.As(err, &verr) {
		t.Fatalf("expected a *ValidationError, got %T: %v", err, err)
	}
	if !strings.Contains(err.Error(), "posted GL entry") {
		t.Fatalf("error = %q, want the posted GL entry message", err)
	}

	notes := "header edit"
	updated, err := d.UpdateIncomingInvoice(bill.ID, UpdateIncomingInvoiceRequest{
		PurchaseOrderID: &po1, Notes: &notes,
	})
	if err != nil {
		t.Fatalf("header save resending the unchanged PO should succeed: %v", err)
	}
	if updated.PurchaseOrderID == nil || *updated.PurchaseOrderID != po1 {
		t.Fatalf("purchaseOrderId = %v, want %q", updated.PurchaseOrderID, po1)
	}
	if updated.Notes == nil || *updated.Notes != notes {
		t.Fatalf("notes = %v, want %q", updated.Notes, notes)
	}
}
