// documentMovements returns the product's movements whose reference is ref.
func documentMovements(t *testing.T, d *Database, productID, ref string) []StockMovement {
	t.Helper()
	movements, err := d.GetProductStockMovements(productID)
	if err != nil {
		t.Fatalf("GetProductStockMovements: %v", err)
	}
	out := make([]StockMovement, 0, len(movements))
	for _, m := range movements {
		if m.Reference != nil && *m.Reference == ref {
			out = append(out, m)
		}
	}
	return out
}

func assertStockMovementDeleteRefused(t *testing.T, d *Database, movementID, wantMessage string) {
	t.Helper()
	_, err := d.DeleteStockMovement(movementID)
	if err == nil {
		t.Fatalf("expected deleting movement %s to be refused", movementID)
	}
	var verr *ValidationError
	if !errors.As(err, &verr) {
		t.Fatalf("expected a *ValidationError, got %T: %v", err, err)
	}
	if !strings.Contains(err.Error(), wantMessage) {
		t.Fatalf("error = %q, want it to contain %q", err, wantMessage)
	}
	if _, err := d.GetStockMovement(movementID); err != nil {
		t.Fatalf("movement should still exist after the refusal: %v", err)
	}
}

// A cancelled delivery's original "out" and restoring "in" are a pair; either
// one must stay undeletable, not just the shipped delivery's own movement.
func TestDeleteStockMovementRefusedForCancelledDeliveryMovements(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGRNITestFixture(t, d, "org-mv-cancel-del", 10, 250)
	fx.receive(t, d, "GR-0001", 10)
	delivery := fx.ship(t, d, "DN-0001", 5)
	if _, err := d.UpdateDeliveryStatus(delivery.ID, "cancelled", nil); err != nil {
		t.Fatalf("UpdateDeliveryStatus(cancelled): %v", err)
	}

	movements := documentMovements(t, d, fx.productID, "DN-0001")
	if len(movements) != 2 {
		t.Fatalf("delivery movements = %d, want 2 (out and restoring in): %+v", len(movements), movements)
	}
	for _, m := range movements {
		assertStockMovementDeleteRefused(t, d, m.ID, "it is part of the delivery's stock history")
	}
}

