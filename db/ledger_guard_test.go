// TestReverseJournalEntryRefusesPaymentEntry: a payment's automatic posting is
// reversed only by voiding the payment, which also reopens the invoice. A
// manual reversal would leave the payment posted (and the invoice paid) with
// no way to void it afterward.
func TestReverseJournalEntryRefusesPaymentEntry(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-reverse-payment")
	inv := fx.createInvoice(t, d, "rev-pay-inv", 1, 1000) // total 1200
	if _, err := d.UpdateInvoiceState(inv.ID, "sent"); err != nil {
		t.Fatalf("UpdateInvoiceState(sent): %v", err)
	}
	bank := accountByCode(t, d, fx.orgID, "1020")

	payment, err := d.CreatePayment(CreatePaymentRequest{
		OrganizationID: fx.orgID, Direction: "inbound", ClientID: &fx.clientID,
		BankAccountID: bank.ID, Amount: 1200, Currency: "EUR", Date: fx.date, Method: "bank_transfer",
		Applications: []CreatePaymentApplicationRequest{{DocumentType: "invoice", DocumentID: inv.ID, Amount: 1200}},
	})
	if err != nil {
		t.Fatalf("CreatePayment: %v", err)
	}
	if payment.JournalEntryID == nil {
		t.Fatal("expected the payment to carry a journal entry id")
	}

	_, err = d.ReverseJournalEntry(*payment.JournalEntryID, "manual reversal", fx.date)
	if err == nil {
		t.Fatal("expected reversing a payment's entry to be refused")
	}
	var ve *ValidationError
	if !errors.As(err, &ve) {
		t.Fatalf("error = %T %v, want a ValidationError", err, err)
	}
	const want = "cannot reverse an entry generated by a payment — undo it through the document instead"
	if got := err.Error(); got != want {
		t.Fatalf("error = %q, want %q", got, want)
	}

	// The refusal must not have flipped the original to 'reversed': the
	// payment stays voidable through its own path.
	entry, err := d.GetJournalEntry(*payment.JournalEntryID)
	if err != nil {
		t.Fatalf("GetJournalEntry: %v", err)
	}
	if entry.Status != "posted" {
		t.Fatalf("payment entry status = %q, want posted after a refused reversal", entry.Status)
	}
	if _, err := d.VoidPayment(payment.ID, fx.date); err != nil {
		t.Fatalf("VoidPayment after a refused manual reversal: %v", err)
	}
}

// TestReverseJournalEntryRefusesClosingEntry: reversing the closing entry
// would reopen a closed year's P&L while the year itself stayed closed.
func TestReverseJournalEntryRefusesClosingEntry(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-reverse-closing")
	fyID := fecFixtureFiscalYearID(t, d, fx.orgID)

	inv := fx.createInvoice(t, d, "rev-close-inv", 2, 1000) // 2000 revenue
	if _, err := d.UpdateInvoiceState(inv.ID, "sent"); err != nil {
		t.Fatalf("UpdateInvoiceState(sent): %v", err)
	}
	if _, err := d.CloseFiscalYear(fyID); err != nil {
		t.Fatalf("CloseFiscalYear: %v", err)
	}
	closing, err := d.postedEntryForSourceDocument("closing", fyID)
	if err != nil || closing == nil {
		t.Fatalf("expected a posted closing entry, err=%v entry=%v", err, closing)
	}

	_, err = d.ReverseJournalEntry(closing.ID, "reopen the year", fx.date)
	if err == nil {
		t.Fatal("expected reversing the closing entry to be refused")
	}
	const want = "cannot reverse an entry generated by a fiscal year closing — undo it through the document instead"
	if got := err.Error(); got != want {
		t.Fatalf("error = %q, want %q", got, want)
	}

	year, err := d.GetFiscalYear(fyID)
	if err != nil {
		t.Fatalf("GetFiscalYear: %v", err)
	}
	if year.Status != "closed" {
		t.Fatalf("year status = %q, want closed", year.Status)
	}
}

func TestReverseJournalEntryStillReversesManualEntry(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newJournalEntryTestFixture(t, d)

	entry, err := d.CreateJournalEntry(CreateJournalEntryRequest{
		OrganizationID: fx.orgID, JournalID: fx.journalID, Date: fx.date,
		Description: "Manual correction",
		Lines: []CreateJournalLineRequest{
			{AccountID: fx.cashAccountID, Debit: 1000},
			{AccountID: fx.salesAccountID, Credit: 1000},
		},
	})
	if err != nil {
		t.Fatalf("CreateJournalEntry: %v", err)
	}
	if _, err := d.PostJournalEntry(entry.ID); err != nil {
		t.Fatalf("PostJournalEntry: %v", err)
	}

	reversal, err := d.ReverseJournalEntry(entry.ID, "correction", fx.date)
	if err != nil {
		t.Fatalf("ReverseJournalEntry(manual): %v", err)
	}
	if reversal.ReversalOfEntryID == nil || *reversal.ReversalOfEntryID != entry.ID {
		t.Fatalf("reversalOfEntryId = %v, want %q", reversal.ReversalOfEntryID, entry.ID)
	}

	original, err := d.GetJournalEntry(entry.ID)
	if err != nil {
		t.Fatalf("GetJournalEntry: %v", err)
	}
	if original.Status != "reversed" {
		t.Fatalf("manual entry status = %q, want reversed", original.Status)
	}
}

func TestPostingIntoClosedPeriodIsRefused(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-closed-period")
	fyID := fecFixtureFiscalYearID(t, d, fx.orgID)

	period, err := d.CreateFiscalPeriod(CreateFiscalPeriodRequest{
		OrganizationID: fx.orgID, FiscalYearID: fyID, Name: "Q1",
		StartDate: 1735689600000, EndDate: 1743465599000, // 2025-01-01 .. 2025-03-31
	})
	if err != nil {
		t.Fatalf("CreateFiscalPeriod: %v", err)
	}
	if _, err := d.UpdateFiscalPeriodStatus(period.ID, "closed"); err != nil {
		t.Fatalf("UpdateFiscalPeriodStatus(closed): %v", err)
	}

	// fx.date (2025-02-01) falls inside the closed period.
	inv := fx.createInvoice(t, d, "closed-period-inv", 1, 1000)
	_, err = d.UpdateInvoiceState(inv.ID, "sent")
	if err == nil {
		t.Fatal("expected posting into a closed fiscal period to be refused")
	}
	const want = "cannot post: the fiscal period covering this date is closed"
	if got := err.Error(); got != want {
		t.Fatalf("error = %q, want %q", got, want)
	}

	// A date outside every period still posts into the open year.
	outsideDate := int64(1751328000000) // 2025-07-01
	subTotal := int64(1000)
	taxTotal := subTotal / 5
	other, err := d.CreateInvoice(CreateInvoiceRequest{
		ID: "outside-period-inv", OrganizationID: fx.orgID, Number: "outside-period-inv",
		ClientID: fx.clientID, Date: outsideDate, Currency: "EUR",
		SubTotal: subTotal, TaxTotal: taxTotal, Total: subTotal + taxTotal,
		LineItems: []CreateInvoiceLineItemRequest{
			{Quantity: 1, UnitPrice: 1000, TaxRate: &fx.taxRateID, ProductID: &fx.productID},
		},
	})
	if err != nil {
		t.Fatalf("CreateInvoice(outside period): %v", err)
	}
	if _, err := d.UpdateInvoiceState(other.ID, "sent"); err != nil {
		t.Fatalf("posting a date outside every period should still succeed: %v", err)
	}
}

func TestFiscalPeriodChangesRefusedInClosedYear(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-period-closed-year")
	fyID := fecFixtureFiscalYearID(t, d, fx.orgID)

	period, err := d.CreateFiscalPeriod(CreateFiscalPeriodRequest{
		OrganizationID: fx.orgID, FiscalYearID: fyID, Name: "Q1",
		StartDate: 1735689600000, EndDate: 1743465599000,
	})
	if err != nil {
		t.Fatalf("CreateFiscalPeriod: %v", err)
	}
	if _, err := d.CloseFiscalYear(fyID); err != nil {
		t.Fatalf("CloseFiscalYear: %v", err)
	}

	const want = "cannot change periods of a closed fiscal year"

	_, err = d.CreateFiscalPeriod(CreateFiscalPeriodRequest{
		OrganizationID: fx.orgID, FiscalYearID: fyID, Name: "Q2",
		StartDate: 1743465600000, EndDate: 1751327999000,
	})
	if err == nil {
		t.Fatal("expected creating a period of a closed year to be refused")
	}
	if got := err.Error(); got != want {
		t.Fatalf("CreateFiscalPeriod error = %q, want %q", got, want)
	}

	_, err = d.UpdateFiscalPeriodStatus(period.ID, "open")
	if err == nil {
		t.Fatal("expected changing a period of a closed year to be refused")
	}
	if got := err.Error(); got != want {
		t.Fatalf("UpdateFiscalPeriodStatus error = %q, want %q", got, want)
	}
}

// TestProfitAndLossOfClosedYearKeepsRevenue: the closing entry zeroes revenue
// and expense, but a P&L over that year must still report the year's own
// activity. The Trial Balance keeps the closing entry and still nets to zero.
func TestProfitAndLossOfClosedYearKeepsRevenue(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-pl-closed-year")
	fyID := fecFixtureFiscalYearID(t, d, fx.orgID)

	inv := fx.createInvoice(t, d, "pl-closed-inv", 2, 1000) // 2000 revenue
	if _, err := d.UpdateInvoiceState(inv.ID, "sent"); err != nil {
		t.Fatalf("UpdateInvoiceState(sent): %v", err)
	}
	if _, err := d.CloseFiscalYear(fyID); err != nil {
		t.Fatalf("CloseFiscalYear: %v", err)
	}

	pl, err := d.GetProfitAndLoss(fx.orgID, 1735689600000, 1767225599000)
	if err != nil {
		t.Fatalf("GetProfitAndLoss: %v", err)
	}
	if pl.TotalRevenue != 2000 {
		t.Fatalf("TotalRevenue = %d, want 2000 after closing", pl.TotalRevenue)
	}
	if pl.TotalExpenses != 0 {
		t.Fatalf("TotalExpenses = %d, want 0", pl.TotalExpenses)
	}
	if pl.NetIncome != 2000 {
		t.Fatalf("NetIncome = %d, want 2000", pl.NetIncome)
	}

	// The Trial Balance still includes the closing entry: the revenue account
	// nets to zero, exactly as before this change.
	tb, err := d.GetTrialBalance(fx.orgID, "", "")
	if err != nil {
		t.Fatalf("GetTrialBalance: %v", err)
	}
	balances := map[string]int64{}
	for _, row := range tb {
		balances[row.AccountID] = row.Debit - row.Credit
	}
	if balances[fx.revenueAccountID] != 0 {
		t.Fatalf("revenue account TB balance = %d, want 0 after closing", balances[fx.revenueAccountID])
	}
}

// Accountants close every period before closing the year. The closing entry
// is dated the year's last day, inside the last (closed) period, and must
// still post: only the closing entry is exempt from the closed-period rule.
func TestCloseFiscalYearAfterEveryPeriodClosed(t *testing.T) {
	t.Parallel()
	d := newTestDB(t)
	fx := newGLPostingTestFixture(t, d, "org-close-after-periods")
	fyID := fecFixtureFiscalYearID(t, d, fx.orgID)
	year, err := d.GetFiscalYear(fyID)
	if err != nil {
		t.Fatalf("GetFiscalYear: %v", err)
	}

	inv := fx.createInvoice(t, d, "close-periods-inv", 2, 1000)
	if _, err := d.UpdateInvoiceState(inv.ID, "sent"); err != nil {
		t.Fatalf("UpdateInvoiceState(sent): %v", err)
	}
	period, err := d.CreateFiscalPeriod(CreateFiscalPeriodRequest{
		OrganizationID: fx.orgID, FiscalYearID: fyID, Name: "Whole year",
		StartDate: year.StartDate, EndDate: year.EndDate,
	})
	if err != nil {
		t.Fatalf("CreateFiscalPeriod: %v", err)
	}
	if _, err := d.UpdateFiscalPeriodStatus(period.ID, "closed"); err != nil {
		t.Fatalf("UpdateFiscalPeriodStatus(closed): %v", err)
	}

	if _, err := d.CloseFiscalYear(fyID); err != nil {
		t.Fatalf("CloseFiscalYear with every period closed: %v", err)
	}
	entry, err := d.postedEntryForSourceDocument("closing", fyID)
	if err != nil || entry == nil {
		t.Fatalf("expected a posted closing entry, err=%v entry=%v", err, entry)
	}
}
